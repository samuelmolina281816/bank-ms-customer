CREATE SEQUENCE IF NOT EXISTS customer_number_seq
    START WITH 10000001
    INCREMENT BY 1
    MINVALUE 10000001
    MAXVALUE 99999999
    NO CYCLE;
@@

CREATE TABLE IF NOT EXISTS customer_profiles (
    customer_type VARCHAR(20) NOT NULL,
    profile_code VARCHAR(30) NOT NULL,
    PRIMARY KEY (customer_type, profile_code),
    CONSTRAINT ck_customer_profiles_type CHECK (customer_type IN ('PERSONAL', 'BUSINESS'))
);
@@

INSERT INTO customer_profiles (customer_type, profile_code)
VALUES ('PERSONAL', 'STANDARD'),
       ('BUSINESS', 'STANDARD'),
       ('PERSONAL', 'VIP'),
       ('BUSINESS', 'PYME')
ON CONFLICT (customer_type, profile_code) DO NOTHING;
@@

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_number BIGINT NOT NULL UNIQUE,
    customer_type VARCHAR(20) NOT NULL,
    document_type VARCHAR(20) NOT NULL,
    document_number VARCHAR(30) NOT NULL,
    profile_code VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_customers_document UNIQUE (document_type, document_number),
    CONSTRAINT ck_customers_customer_number CHECK (customer_number BETWEEN 10000000 AND 99999999),
    CONSTRAINT ck_customers_document_type CHECK (document_type IN ('DNI', 'RUC', 'CE', 'PASSPORT')),
    CONSTRAINT ck_customers_document_number CHECK (
        (document_type = 'DNI' AND document_number ~ '^[0-9]{8}$')
        OR (document_type = 'RUC' AND document_number ~ '^[0-9]{11}$')
        OR (document_type IN ('CE', 'PASSPORT') AND document_number ~ '^[A-Za-z0-9]{5,12}$')
    ),
    CONSTRAINT ck_customers_type_document CHECK (
        (customer_type = 'PERSONAL' AND document_type IN ('DNI', 'CE', 'PASSPORT'))
        OR (customer_type = 'BUSINESS' AND document_type = 'RUC')
    ),
    CONSTRAINT ck_customers_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_customers_profile FOREIGN KEY (customer_type, profile_code)
        REFERENCES customer_profiles (customer_type, profile_code)
);
@@

CREATE INDEX IF NOT EXISTS ix_customers_status ON customers (status);
@@

CREATE TABLE IF NOT EXISTS personal_customer (
    customer_id BIGINT PRIMARY KEY REFERENCES customers (id) ON DELETE CASCADE,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    CONSTRAINT ck_personal_customer_names CHECK (
        btrim(first_name) <> '' AND btrim(last_name) <> ''
    )
);
@@

CREATE TABLE IF NOT EXISTS business_customer (
    customer_id BIGINT PRIMARY KEY REFERENCES customers (id) ON DELETE CASCADE,
    business_name VARCHAR(180) NOT NULL,
    CONSTRAINT ck_business_customer_name CHECK (btrim(business_name) <> '')
);
@@

CREATE TABLE IF NOT EXISTS customer_contact (
    customer_id BIGINT PRIMARY KEY REFERENCES customers (id) ON DELETE CASCADE,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    address VARCHAR(250)
);
@@

CREATE OR REPLACE FUNCTION assert_customer_aggregate_integrity(checked_customer_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    actual_customer_type VARCHAR(20);
    personal_count INTEGER;
    business_count INTEGER;
    contact_count INTEGER;
BEGIN
    SELECT customer_type
    INTO actual_customer_type
    FROM customers
    WHERE id = checked_customer_id;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT COUNT(*) INTO personal_count
    FROM personal_customer WHERE customer_id = checked_customer_id;

    SELECT COUNT(*) INTO business_count
    FROM business_customer WHERE customer_id = checked_customer_id;

    SELECT COUNT(*) INTO contact_count
    FROM customer_contact WHERE customer_id = checked_customer_id;

    IF ((actual_customer_type = 'PERSONAL' AND personal_count = 1 AND business_count = 0)
        OR (actual_customer_type = 'BUSINESS' AND business_count = 1 AND personal_count = 0))
       AND contact_count = 1 THEN
        RETURN;
    END IF;

    RAISE EXCEPTION 'Customer % must have exactly one matching subtype and one contact record', checked_customer_id
        USING ERRCODE = '23514',
              CONSTRAINT = 'ck_customers_aggregate_integrity';
END;
$$;
@@

CREATE OR REPLACE FUNCTION enforce_customer_aggregate_integrity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    affected_customer_id BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'customers' THEN
        affected_customer_id := COALESCE(NEW.id, OLD.id);
        PERFORM assert_customer_aggregate_integrity(affected_customer_id);
    ELSE
        IF TG_OP = 'UPDATE' AND NEW.customer_id <> OLD.customer_id THEN
            PERFORM assert_customer_aggregate_integrity(OLD.customer_id);
        END IF;
        affected_customer_id := COALESCE(NEW.customer_id, OLD.customer_id);
        PERFORM assert_customer_aggregate_integrity(affected_customer_id);
    END IF;
    RETURN NULL;
END;
$$;
@@

DROP TRIGGER IF EXISTS ct_customers_subtype_integrity ON customers;
@@
CREATE CONSTRAINT TRIGGER ct_customers_subtype_integrity
AFTER INSERT OR UPDATE ON customers
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION enforce_customer_aggregate_integrity();
@@

